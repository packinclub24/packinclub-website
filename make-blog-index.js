/*
  Packin Club: make a SMALL blog list for the homepage.

  WHY: blog-data.js holds the full text of every article (about 260 KB). The homepage only shows
  3 article cards (tag, thumbnail, title, short excerpt), so loading all 260 KB there slows the page down.
  This tool reads blog-data.js and writes blog-index.js, which keeps ONLY what the homepage cards need.

  USE (in the project root, the folder with index.html):
      node make-blog-index.js

  RUN IT AGAIN every time you add or edit a blog post in blog-data.js. Then run: node prerender.js index.html
*/
const fs = require('fs'), path = require('path'), vm = require('vm');
const ROOT = __dirname;
const sb = { window: {}, console };
vm.createContext(sb);
vm.runInContext(fs.readFileSync(path.join(ROOT, 'blog-data.js'), 'utf8'), sb);
const B = sb.window.PACKIN_BLOG;
if (!B || !B.posts || !B.posts.length) { console.error('Could not read posts from blog-data.js'); process.exit(1); }

// only the fields the homepage cards use
const light = B.posts.map(p => ({
  title: p.title, cat: p.cat, slug: p.slug, date: p.date,
  excerpt: p.excerpt, thumb: p.thumb, heroBg: p.heroBg
}));

const out =
'/* GENERATED by make-blog-index.js from blog-data.js. Do not edit by hand. Re-run: node make-blog-index.js */\n' +
'window.PACKIN_BLOG = { posts: ' + JSON.stringify(light) + ' };\n';
fs.writeFileSync(path.join(ROOT, 'blog-index.js'), out, 'utf8');
console.log('wrote blog-index.js: ' + light.length + ' posts, ' + Math.round(out.length / 1024) + ' KB (blog-data.js is ' + Math.round(fs.statSync(path.join(ROOT, 'blog-data.js')).size / 1024) + ' KB)');
